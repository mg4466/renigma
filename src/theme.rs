pub fn lookup(name: &str) -> Option<Theme> {
    THEMES.iter().find(|t| t.name == name).copied()
}

pub fn get(name: &str) -> Theme {
    lookup(name).unwrap_or(THEMES[0])
}

pub fn theme_names() -> Vec<&'static str> {
    THEMES.iter().map(|t| t.name).collect()
}
